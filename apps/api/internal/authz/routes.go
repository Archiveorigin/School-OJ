func NormalizePath(path string) string {
	if path == "/api/v1" || strings.HasPrefix(path, "/api/v1/") {
		return strings.TrimPrefix(path, "/api/v1")
	}
	return strings.TrimPrefix(path, "/api")
}
func Route(method, path string) (RoutePolicy, bool) {
	path = NormalizePath(path)
	for _, entry := range Routes {
		if entry.Method == method && entry.Path == path {
			return entry, true
		}
	}
	return RoutePolicy{}, false
}
func CheckRoute(ctx Context, route RoutePolicy) Decision {
	registered, exists := Route(route.Method, route.Path)
	if !exists || registered != route {
		return Decision{Reason: "POLICY_UNREGISTERED"}
	}
	if route.Access == "public" {
		return Decision{true, "PUBLIC_ROUTE"}
	}
	if !knownContext(ctx) {
		return Decision{Reason: "IDENTITY_UNDEFINED"}
	}
	if route.Access == "authenticated" {
		return Decision{true, "AUTHENTICATED"}
	}
	return Check(ctx, route.Access, Resource{})
}
