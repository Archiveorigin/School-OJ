func (s Server) Router() *gin.Engine {
	router := gin.New()
	router.Use(gin.LoggerWithFormatter(func(p gin.LogFormatterParams) string {
		return fmt.Sprintf("%s %s %d %s\n", p.Method, strings.SplitN(p.Path, "?", 2)[0], p.StatusCode, p.Latency)
	}), gin.Recovery(), middleware.SecurityHeaders(), middleware.ObserveAPIVersion(s.Redis), s.authorizationAudit())
	if err := router.SetTrustedProxies(s.Cfg.TrustedProxies); err != nil {
		panic(fmt.Errorf("configure trusted proxies: %w", err))
	}

	allowedOrigins := s.Cfg.CORSOrigins
	if len(allowedOrigins) == 0 {
		allowedOrigins = []string{"http://localhost:3000", "http://localhost:5173"}
	}
	allowAllOrigins := len(allowedOrigins) == 1 && strings.TrimSpace(allowedOrigins[0]) == "*"
	if allowAllOrigins {
		allowedOrigins = nil
	}
	router.Use(cors.New(cors.Config{
		AllowAllOrigins:  allowAllOrigins,
		AllowOrigins:     allowedOrigins,
		AllowMethods:     []string{"GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"},
		AllowHeaders:     []string{"Authorization", "Content-Type"},
		ExposeHeaders:    []string{"Content-Length", "X-RateLimit-Limit", "X-RateLimit-Remaining", "Retry-After", "X-API-Version"},
		AllowCredentials: !allowAllOrigins,
		MaxAge:           12 * time.Hour,
	}))

	router.GET("/healthz", s.health)
	router.GET("/metrics", middleware.APIMetrics(s.Redis))
	router.GET("/openapi.json", func(c *gin.Context) {
		c.Data(200, "application/json; charset=utf-8", openapi.Document())
	})
	s.registerAPIRoutes(router.Group("/api"))
	s.registerAPIRoutes(router.Group("/api/v1"))
	router.NoRoute(middleware.OptionalAuth(s.DB, s.Cfg.JWTSecret), s.enforceExamScope, func(c *gin.Context) { c.JSON(404, gin.H{"error": "not found"}) })
	for _, route := range router.Routes() {
		if strings.HasPrefix(route.Path, "/api/") {
			if _, ok := authz.Route(route.Method, route.Path); !ok {
				panic("unregistered authorization route: " + route.Method + " " + route.Path)
			}
		}
	}
	return router
}

