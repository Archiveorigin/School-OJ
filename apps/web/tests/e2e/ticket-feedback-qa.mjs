async function api(page, resource, method='GET', data, expected=200) {
  if(expected>=400) expectedErrors.add(`/api${resource.split('?')[0]}`)
  const result=await page.evaluate(async ({resource,method,data})=>{
    const r=await fetch(`/api${resource}`,{method,headers:{Authorization:`Bearer ${localStorage.getItem('school-oj-token')}`,'Content-Type':'application/json'},body:data===undefined?undefined:JSON.stringify(data)})
    return {status:r.status,data:await r.json()}
  },{resource,method,data})
  assert.equal(result.status,expected,`${resource}: ${JSON.stringify(result.data)}`)
  return result.data
}
