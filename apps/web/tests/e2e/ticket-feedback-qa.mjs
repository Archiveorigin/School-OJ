async function feedback(page, board, description, action='修改', attachments=[]) {
  await board.getByRole('button',{name:'提交反馈',exact:true}).click()
  if(action!=='修改') await type(page,board,action)
  await board.getByPlaceholder(/请具体说明问题/).fill(description)
  if(attachments.length) await board.locator('input[type=file]').setInputFiles(attachments)
  const pending=page.waitForResponse(r=>r.request().method()==='POST' && /change-tickets$/.test(new URL(r.url()).pathname))
  await board.getByRole('button',{name:'提交工单',exact:true}).click()
  const response=await pending; assert.equal(response.status(),201,await response.text())
  const ticket=await response.json(); await board.getByRole('heading',{name:`工单 #${ticket.id}`,exact:true}).waitFor()
  return ticket
}
